#!/usr/bin/env python3
"""Freshness: every CSV must be NEWER than its producer AND newer than the raw data it reads.

Why a project-specific table instead of the generic --auto mode: --auto infers the producer from
the FILE NAME (results/foo.csv <- code/foo.py). No name matches here: matrix.csv is produced by
g2_realreport.py, tau.csv by g2_tau.py, g3-regime.csv by g3_paper_artifacts.py. Running --auto
returns exactly the right answer, "no pair could be inferred, so NOTHING WAS CHECKED". That report
is correct, and the correct fix is to DECLARE the mapping, not to loosen --auto.

One difference matters: these CSVs do not read from a shared `data.py`, they read from raw checker
logs. Those logs are MEASURED DATA and cannot be regenerated by re-running code, because re-running
calls a model and produces different numbers. So the rule here is: a CSV must be newer than its
producer AND newer than the raw logs it consumes. A raw log newer than the CSV means a new
measurement exists that the tables have not been rebuilt from.

`g2_tables.py` deliberately appears only as the producer of the tables it writes: it also READS
several CSVs to emit .tex, which puts it downstream. Confusing consumer with producer would make
the provenance table meaningless.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TBL = os.path.join(ROOT, "paper", "tables")
FIGS = os.path.join(ROOT, "paper", "figs")

# csv -> (directory holding the csv, the script that produces it, the raw inputs that script reads)
RAW_G2 = [f"raw/{n}" for n in ["g2-strict-20260813.txt","g2-strict-b-20260813.txt","g2-strict-r3-20260813.txt",
          "g2-moderate-20260813.txt","g2-moderate-r2-20260813.txt","g2-moderate-r3-20260813.txt",
          "g2-lenient-20260813.txt","g2-lenient-r2-20260813.txt","g2-lenient-r3-20260813.txt"]]
RAW_G3 = [f"raw/g3-{t}-r{i}-20260813.txt" for t in ("opus","sonnet","haiku") for i in (1,2,3)]
RAW_G4 = [f"raw/g4-{t}-s{i}-20260813.txt" for t in ("opus","sonnet","haiku") for i in (1,2,3)]
RAW_H  = [f"raw/h-{t}-r{i}-20260813.txt" for t in ("opus","sonnet","haiku") for i in (1,2,3)]

MAP = {
    "compose.csv":    (TBL,  "g2_tables.py",          []),
    "corpus.csv":     (TBL,  "g2_tables.py",          []),
    # g4_analyze.py WRITES g4_verdicts.json and then reads it back, so the verdict file is an
    # OUTPUT, not an input. Listing it here would make the gate compare a file against itself.
    # The re-run reports read DIRECTLY from raw/, so their dependencies are THE RAW LOG FILES
    # rather than a verdict JSON. The raw log is the source of truth.
    "rerun-g2.csv":        (TBL, "rerun_report.py", RAW_G2),
    "rerun-g3.csv":        (TBL, "rerun_report.py", RAW_G3),
    "rerun-g4.csv":        (TBL, "rerun_report.py", RAW_G4),
    "rerun-g2-matrix.csv": (TBL, "rerun_report.py", RAW_G2),
    "rerun-g3-matrix.csv": (TBL, "rerun_report.py", RAW_G3),
    "rerun-modes.csv":     (TBL, "rerun_report.py", RAW_G2 + RAW_G4),
    "hard-corpus.csv":          (TBL, "h_score.py", RAW_H),
    "hard-blindspot-shift.csv": (TBL, "h_score.py", RAW_H),
}

# local modules each producer imports (the CSV must also be newer than these)
IMPORTS = {
    "g2_realreport.py":      ["g2_corpus.py", "g2_gates.py"],
    "g2_tau.py":             ["g2_corpus.py", "g2_gates.py"],
    "g3_paper_artifacts.py": ["g2_corpus.py", "g2_gates.py"],
    "g2_tables.py":          ["g2_corpus.py"],
    "g4_analyze.py":         ["g4_corpus.py"],
    "rerun_report.py":       ["g2_corpus.py", "g2_gates.py", "g4_corpus.py"],
    "h_score.py":            ["h_corpus.py"],
}


def mtime(p):
    return os.path.getmtime(p) if os.path.exists(p) else None


def main():
    stale, missing, checked = [], [], 0
    print("check_freshness -- a CSV must be newer than its producer, its imports, and its raw data\n")
    for csv, (d, prod, raws) in sorted(MAP.items()):
        cpath = os.path.join(d, csv)
        ppath = os.path.join(HERE, prod)
        ct = mtime(cpath)
        if ct is None:
            missing.append(f"{csv}: DOES NOT EXIST ({cpath})")
            continue
        deps = [(prod, ppath)]
        deps += [(m, os.path.join(HERE, m)) for m in IMPORTS.get(prod, [])]
        deps += [(r, os.path.join(HERE, r)) for r in raws]
        worst = []
        for name, dp in deps:
            dt = mtime(dp)
            if dt is None:
                missing.append(f"{csv}: missing dependency -- {name}")
                continue
            checked += 1
            if dt > ct:
                worst.append(f"{name} is {(dt - ct) / 60:.1f} min newer")
        if worst:
            stale.append(f"{csv}: STALE -- " + "; ".join(worst))
        else:
            print(f"  {csv:16s} FRESH  (producer {prod}, {len(deps)} deps)")

    print(f"\n  (csv, dependency) pairs compared: {checked}")
    if checked == 0:
        print("  0 pairs compared => this gate checked NOTHING. That is BROKEN, not clean.")
        return 4
    for m in missing:
        print("  MISSING " + m)
    for s in stale:
        print("  STALE   " + s)
    if stale or missing:
        print(f"\nFAIL -- {len(stale)} stale files, {len(missing)} missing dependencies.")
        return 2
    print(f"\nPASS -- {len(MAP)} CSVs, all newer than their producers and their raw data.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
