#!/usr/bin/env python3
"""Freshness: every CSV must be NEWER than its producer AND newer than the raw data it reads.

Why a project-specific table instead of the generic --auto mode: --auto infers the producer from
the FILE NAME (results/foo.csv <- code/foo.py). No name matches here: matrix.csv is produced by
rerun_report.py, hard-corpus.csv by h_score.py, compose.csv by corpus_tables.py. Running --auto
returns exactly the right answer, "no pair could be inferred, so NOTHING WAS CHECKED". That report
is correct, and the correct fix is to DECLARE the mapping, not to loosen --auto.

One difference matters: these CSVs do not read from a shared `data.py`, they read from raw checker
logs. Those logs are MEASURED DATA and cannot be regenerated by re-running code, because re-running
calls a model and produces different numbers. So the rule here is: a CSV must be newer than its
producer AND newer than the raw logs it consumes. A raw log newer than the CSV means a new
measurement exists that the tables have not been rebuilt from.

`g2_tables.py` deliberately appears only as the producer of the tables it writes: it also READS
several CSVs to emit .tex, which puts it downstream. Confusing consumer with producer would make
the provenance table meaningless.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TBL = os.path.join(ROOT, "paper", "tables")
FIGS = os.path.join(ROOT, "paper", "figs")

# csv -> (directory holding the csv, the script that produces it, the raw inputs that script reads)
RAW_G2 = [f"raw/{n}" for n in ["g2-strict-20260813.txt","g2-strict-b-20260813.txt","g2-strict-r3-20260813.txt",
          "g2-moderate-20260813.txt","g2-moderate-r2-20260813.txt","g2-moderate-r3-20260813.txt",
          "g2-lenient-20260813.txt","g2-lenient-r2-20260813.txt","g2-lenient-r3-20260813.txt"]]
RAW_G3 = [f"raw/g3-{t}-r{i}-20260813.txt" for t in ("opus","sonnet","haiku") for i in (1,2,3)]
RAW_G4 = [f"raw/g4-{t}-s{i}-20260813.txt" for t in ("opus","sonnet","haiku") for i in (1,2,3)]
RAW_H  = [f"raw/h-{t}-r{i}-20260813.txt" for t in ("opus","sonnet","haiku") for i in (1,2,3)]
# Second model family, added 14/08/2026. Listed explicitly for the same reason as the Claude runs:
# a CSV must be newer than every log it consumes, and a glob would silently absorb a new arm.
RAW_GEM = ([f"raw/h-gfliteT10-r{i}-20260814.txt" for i in range(1, 6)]
           + [f"raw/h-gfliteT00-r{i}-20260814.txt" for i in range(1, 6)]
           + [f"raw/h-gflashT10-r{i}-20260814.txt" for i in range(1, 6)]
           + [f"raw/h-g31liteT10-r{i}-20260814.txt" for i in range(1, 4)])

MAP = {
    "compose.csv":    (TBL,  "corpus_tables.py",      []),
    "corpus.csv":     (TBL,  "corpus_tables.py",      []),
    # g4_analyze.py WRITES g4_verdicts.json and then reads it back, so the verdict file is an
    # OUTPUT, not an input. Listing it here would make the gate compare a file against itself.
    # The re-run reports read DIRECTLY from raw/, so their dependencies are THE RAW LOG FILES
    # rather than a verdict JSON. The raw log is the source of truth.
    "rerun-g2.csv":        (TBL, "rerun_report.py", RAW_G2),
    "rerun-g3.csv":        (TBL, "rerun_report.py", RAW_G3),
    "rerun-g4.csv":        (TBL, "rerun_report.py", RAW_G4),
    "rerun-g2-matrix.csv": (TBL, "rerun_report.py", RAW_G2),
    "rerun-g3-matrix.csv": (TBL, "rerun_report.py", RAW_G3),
    "rerun-modes.csv":     (TBL, "rerun_report.py", RAW_G2 + RAW_G4),
    "rerun-paired.csv":    (TBL, "rerun_report.py", RAW_G2),
    "hard-corpus.csv":          (TBL, "h_score.py", RAW_H + RAW_GEM),
    "hard-blindspot-shift.csv": (TBL, "h_score.py", RAW_H),
    "hard-crossfamily.csv":     (TBL, "h_score.py", RAW_H + RAW_GEM),
    "hard-matrix.csv":          (TBL, "h_matrix.py", RAW_H),
    "hard-paired.csv":          (TBL, "h_matrix.py", RAW_H),
    # Counts of cells in which an ablation differs from ATTEST. Its inputs are the three released
    # ablation matrices, which are themselves outputs, so the chain is matrices -> this file; the
    # gate still reaches the raw logs through the freshness of those matrices.
    "ablation-nulls.csv":       (TBL, "ablation_nulls.py",
                                 [os.path.join(TBL, n) for n in
                                  ("hard-matrix.csv", "rerun-g3-matrix.csv", "rerun-g2-matrix.csv")]),
}

# local modules each producer imports (the CSV must also be newer than these)
IMPORTS = {
    "corpus_tables.py":      ["g2_corpus.py"],
    "rerun_report.py":       ["g2_corpus.py", "g2_gates.py", "g4_corpus.py"],
    "h_score.py":            ["h_corpus.py"],
    "h_matrix.py":           ["h_corpus.py", "g2_gates.py"],
}


def hai_so_co_khop(ra):
    """MAP here and `csv-producer.map` are two registries for one fact, so they drift.

    Why this exists. The module docstring records that hard-matrix.csv and hard-paired.csv were
    registered in `csv-producer.map` on 13/08/2026 and NOT here, so this gate did not check them.
    Ca 23/10/2026 it happened again, with ablation-nulls.csv. A duplicated registry that nobody
    compares will keep doing this, so compare them and report any disagreement.
    """
    p = os.path.join(HERE, "csv-producer.map")
    if not os.path.exists(p):
        ra.append("thieu code/csv-producer.map, khong doi chieu duoc hai so")
        return
    tep = {}
    with open(p, encoding="utf-8") as f:
        for ln in f:
            ln = ln.strip()
            if not ln or ln.startswith("#") or "=" not in ln:
                continue
            k, v = ln.split("=", 1)
            tep[k.strip()] = v.strip()
    for k in sorted(k for k in tep if k.endswith(".csv") and k not in MAP):
        ra.append("`%s` co trong csv-producer.map nhung KHONG co trong MAP: cong nay bo qua no" % k)
    for k in sorted(k for k in MAP if k not in tep):
        ra.append("`%s` co trong MAP nhung KHONG co trong csv-producer.map" % k)
    for k in sorted(set(tep) & set(MAP)):
        if tep[k] != MAP[k][1]:
            ra.append("`%s` khai bo sinh khac nhau: tep noi %s, MAP noi %s"
                      % (k, tep[k], MAP[k][1]))


def mtime(p):
    return os.path.getmtime(p) if os.path.exists(p) else None


def unlisted_csvs():
    """Every CSV in the tables directory that MAP does not mention.

    Why this exists. MAP was hand-maintained, and two CSVs added on 13/08/2026 (hard-matrix.csv,
    hard-paired.csv) were registered in `csv-producer.map` but not here, because the project carries
    two copies of the same mapping. The gate then checked 10 files, said "PASS -- 10 CSVs", and the
    two it skipped were precisely the ones carrying the paper's new headline result. Nothing in the
    output distinguished "10 checked and all fresh" from "10 checked, 2 ignored".

    The general rule this enforces: a completeness gate must compare its checklist against what is
    actually on disk, or adding a new output silently exempts that output from checking. Adding a
    file must never be the way to avoid a gate.
    """
    if not os.path.isdir(TBL):
        return []
    return sorted(n for n in os.listdir(TBL) if n.endswith(".csv") and n not in MAP)


def main():
    stale, missing, checked = [], [], 0
    print("check_freshness -- a CSV must be newer than its producer, its imports, and its raw data\n")
    orphans = unlisted_csvs()
    for csv, (d, prod, raws) in sorted(MAP.items()):
        cpath = os.path.join(d, csv)
        ppath = os.path.join(HERE, prod)
        ct = mtime(cpath)
        if ct is None:
            missing.append(f"{csv}: DOES NOT EXIST ({cpath})")
            continue
        deps = [(prod, ppath)]
        deps += [(m, os.path.join(HERE, m)) for m in IMPORTS.get(prod, [])]
        deps += [(r, os.path.join(HERE, r)) for r in raws]
        worst = []
        for name, dp in deps:
            dt = mtime(dp)
            if dt is None:
                missing.append(f"{csv}: missing dependency -- {name}")
                continue
            checked += 1
            if dt > ct:
                worst.append(f"{name} is {(dt - ct) / 60:.1f} min newer")
        if worst:
            stale.append(f"{csv}: STALE -- " + "; ".join(worst))
        else:
            print(f"  {csv:16s} FRESH  (producer {prod}, {len(deps)} deps)")

    print(f"\n  (csv, dependency) pairs compared: {checked}")
    if checked == 0:
        print("  0 pairs compared => this gate checked NOTHING. That is BROKEN, not clean.")
        return 4
    for m in missing:
        print("  MISSING " + m)
    for s in stale:
        print("  STALE   " + s)
    if stale or missing:
        print(f"\nFAIL -- {len(stale)} stale files, {len(missing)} missing dependencies.")
        return 2
    if orphans:
        print(f"\nBLOCK -- {len(orphans)} CSV(s) in {os.path.relpath(TBL, ROOT)} are NOT in MAP and "
              f"were therefore NOT CHECKED:")
        for o in orphans:
            print(f"      {o}")
        print("  An unlisted output is an unchecked output. Declare its producer and raw inputs.")
        return 2
    lech = []
    hai_so_co_khop(lech)
    if lech:
        print(f"\nBLOCK -- {len(lech)} chenh lech giua MAP va csv-producer.map:")
        for l in lech:
            print(f"      {l}")
        print("  Hai so cho cung mot su that thi se lech. Sua ca hai, dung sua mot.")
        return 2
    print(f"\nPASS -- {len(MAP)} CSVs (every CSV present in the directory), all newer than their "
          f"producers and their raw data; MAP khop csv-producer.map.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
