#!/usr/bin/env python3
"""Emit the cross-family figure as TikZ, derived from hard-crossfamily.csv rather than drawn by hand.

The finding this figure carries is about SHAPE: a checker either sees a defect class or is blind to
it, and intermediate cells are rare. A bar chart of mean detection would hide exactly that, because
a mean of 0.6 describes a state that never occurred. So one glyph per (checker, class, run):

    filled square   the checker caught every instance of that class in that run
    open square     it caught none
    half square     anything in between, which is what makes the rare cells visible as rare

Role is encoded by FILL PATTERN, not hue, so the figure survives greyscale printing. That is checked
mechanically by the pipeline's figure gate, which measures luminance separation rather than looking
for a house macro name.

Writes paper/fig-crossfamily.tex, which main.tex \\input's inside a figure environment.
"""
import csv
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "..", "paper", "tables", "hard-crossfamily.csv")
OUT = os.path.join(HERE, "..", "paper", "fig-crossfamily.tex")

# Display names. The paper is double-blind about the authors, not about the models, but it refers to
# the two families as A and B in the table, so keep that consistent here.
LABEL = {"opus": "A: strong", "sonnet": "A: mid", "haiku": "A: cheap",
         "gflashT10": "B: flash", "g31liteT10": "B: lite (prev)",
         "gfliteT10": r"B: lite, $T{=}1$", "gfliteT00": r"B: lite, $T{=}0$"}
ORDER = ["opus", "sonnet", "haiku", "gflashT10", "g31liteT10", "gfliteT10", "gfliteT00"]
# Row labels are what set the figure's width, and the long ones pushed it 14pt past the column
# without LaTeX erroring (only an Overfull \hbox nobody was reading). Short forms; the caption
# spells out what each abbreviates.
SHORT = {"subset-superlative": "subset sup.",
         "mechanism-vs-decomposition": "mechanism",
         "false-exclusivity": "exclusivity",
         "empty-filter": "empty filter",
         "selection-regression": "selection"}


def main():
    rows = list(csv.DictReader(open(CSV)))
    if not rows:
        raise SystemExit("BLOCK: hard-crossfamily.csv is empty. Empty is broken, not clean.")
    cells = defaultdict(list)
    for r in rows:
        cells[(r["checker"], r["defect_class"])].append(float(r["detect"]))
    classes = [c for c in SHORT if any(k[1] == c for k in cells)]
    checkers = [c for c in ORDER if any(k[0] == c for k in cells)]
    unknown = sorted({r["checker"] for r in rows} - set(ORDER))
    if unknown:
        raise SystemExit(f"BLOCK: checker(s) with no display label: {unknown}. A figure that "
                         f"silently drops a condition is worse than no figure.")

    # One glyph per (checker, class), not per run, so the grid fits a single column. The per-run
    # detail stays in hard-crossfamily.csv; what the figure has to carry is the PATTERN, and a
    # 5x7 grid carries it at a size a reader can actually see. An earlier version drew one square
    # per run, which needed 130mm and ran off the column edge -- cutting off the `empty-filter`
    # column, the one the caption tells the reader to look at.
    #   solid  detected every instance, in every run
    #   empty  detected none, in every run
    #   half   disagreed between runs (the rare case, and the one worth seeing)
    CW, RH, g = 7.2, 6.2, 3.3
    SHORTCK = {"opus": "A str", "sonnet": "A mid", "haiku": "A chp", "gflashT10": "B fl",
               "g31liteT10": "B lt$'$", "gfliteT10": "B lt$_1$", "gfliteT00": "B lt$_0$"}
    L = []
    L.append("% GENERATED by code/fig_crossfamily.py from tables/hard-crossfamily.csv. Do not edit.")
    L.append("\\begin{tikzpicture}[x=1mm,y=1mm,")
    L.append("  hit/.style={draw=dphGray,line width=.35pt,fill=dphGray},")
    L.append("  miss/.style={draw=dphGray,line width=.35pt,fill=white},")
    L.append("  part/.style={draw=dphGray,line width=.35pt,fill=dphGray!45},")
    L.append("  lb/.style={font=\\footnotesize,anchor=east},")
    L.append("  hd/.style={font=\\footnotesize,anchor=base}]")
    for ci, ch in enumerate(checkers):
        L.append(f"\\node[hd] at ({ci * CW + g / 2:.1f},{len(classes) * RH + 1.0:.1f}) "
                 f"{{{SHORTCK[ch]}}};")
    for ri, cls in enumerate(classes):
        y = (len(classes) - 1 - ri) * RH
        lab = SHORT[cls].replace("\\\\", " ")
        L.append(f"\\node[lb] at (-1.5,{y + g / 2:.1f}) {{{lab}}};")
        for ci, ch in enumerate(checkers):
            vals = cells[(ch, cls)]
            st = "hit" if all(v == 1.0 for v in vals) else (
                 "miss" if all(v == 0.0 for v in vals) else "part")
            x = ci * CW
            L.append(f"\\draw[{st}] ({x:.1f},{y:.1f}) rectangle ({x + g:.1f},{y + g:.1f});")
    ly = -6.0
    for x, st, txt in ((0, "hit", "always caught"), (21.5, "miss", "never caught"),
                       (43, "part", "varied")):
        L.append(f"\\draw[{st}] ({x},{ly}) rectangle ({x + g},{ly + g});")
        L.append(f"\\node[font=\\footnotesize,anchor=west] at ({x + g + 1.4},{ly + g / 2:.1f}) "
                 f"{{{txt}}};")
    L.append("\\end{tikzpicture}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    n = sum(len(v) for v in cells.values())
    ext = sum(1 for v in cells.values() for x in v if x in (0.0, 1.0))
    print(f"  wrote fig-crossfamily.tex: {len(checkers)} checkers x {len(classes)} classes, "
          f"{n} glyphs, {ext} extremal")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
